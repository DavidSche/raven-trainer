#: Official registry weight names (basename lookup, rf-detr downloads to RF_HOME).
_OFFICIAL_WEIGHT_NAMES = frozenset({
    "rf-detr-nano.pth", "rf-detr-small.pth", "rf-detr-base.pth",
    "rf-detr-medium.pth", "rf-detr-large.pth", "rf-detr-large-2026.pth",
    "rf-detr-seg-nano.pt", "rf-detr-seg-small.pt", "rf-detr-seg-medium.pt",
    "rf-detr-seg-large.pt", "rf-detr-seg-xlarge.pt", "rf-detr-seg-2xlarge.pt",
    "rf-detr-xlarge.pth", "rf-detr-2xlarge.pth",
})


def validate_pretrain_weights(value: Any) -> Optional[str]:
    """Pre-check ``pretrain_weights``: local path or official registry name.

    rf-detr resolves weights by basename against its registry and silently
    skips unknown names — give a clear error here instead (P1-8).
    """
    if value is None or value == "":
        return None
    s = str(value)
    # URL is never supported upstream
    if s.startswith(("http://", "https://")):
        raise ValueError(
            f"pretrain_weights does not support URLs: {s!r}. "
            "Use a local .pth/.pt path or an official registry weight name "
            "(e.g. rf-detr-medium.pth)."
        )
    p = Path(s)
    if p.is_absolute() or (p.parent != Path(".") and not s.startswith("~")):
        # looks like a path — must exist (allow ~ expansion)
        expanded = p.expanduser()
        if not expanded.exists():
            raise FileNotFoundError(
                f"pretrain_weights local path not found: {s}"
            )
        return str(expanded)
    # bare name — must be in official registry
    if s not in _OFFICIAL_WEIGHT_NAMES:
        raise ValueError(
            f"pretrain_weights {s!r} is not a local file and not an official "
            "RF-DETR registry weight name. Supported official names: "
            f"{sorted(_OFFICIAL_WEIGHT_NAMES)}"
        )
    return s


