#: TrainConfig fields supported by rf-detr 1.10.0.dev — generated by
#: ``set(TrainConfig.model_fields.keys())`` (extra="forbid"). Only these keys are
#: forwarded to ``model.train()``; everything else is either consumed by the
#: adapter itself or dropped with a warning (any other key would raise a hard
#: ValidationError deep inside upstream, e.g. ``val_interval``/``max_epochs``/
#: ``amp``/``compile`` are NOT TrainConfig fields).
_TRAIN_WHITELIST = frozenset({
    # data / runtime
    "epochs", "batch_size", "num_workers", "output_dir", "dataset_dir",
    "dataset_file", "run", "project", "seed",
    # optimization
    "lr", "lr_encoder", "lr_drop", "weight_decay",
    "warmup_epochs", "grad_accum_steps",
    "use_ema", "ema_decay", "amp_dtype",
    # schedule / early stopping
    "early_stopping", "early_stopping_patience",
    "early_stopping_min_delta", "checkpoint_interval", "skip_best_epochs",
    # validation
    "eval_interval",
    # logging / UI
    "progress_bar", "tensorboard", "wandb", "mlflow", "clearml", "notes",
    # dataset specifics
    "drop_path",
})

#: Kwargs absorbed by the adapter itself (not forwarded to upstream).
_ADAPTER_CONSUMED_KEYS = frozenset({
    "model", "resolution", "imgsz", "device", "task", "weights",
    "name", "project", "pretrain_weights", "num_classes", "nc",
    "dataset_dir", "output_dir",
})


@dataclass(frozen=True)
class VariantInfo:
    """Resolved variant metadata for a Raven model name."""

    model_name: str            # canonical Raven name, e.g. rf-detr-medium
    variant_cls: str           # rfdetr class name, e.g. RFDETRMedium
    config_cls: str            # rfdetr config class name, e.g. RFDETRMediumConfig
    resolution: int            # default input resolution (square)
    is_seg: bool = False
    deprecated: bool = False


def resolve_variant(model_name: Optional[str]) -> VariantInfo:
    """Resolve a Raven model name to its rf-detr variant metadata.

    Raises ValueError for unknown / unsupported names (whitelist validation).
    """
    if not model_name:
        raise ValueError("model name is required for rfdetr backend (e.g. rf-detr-medium)")
    canonical = MODEL_VARIANT_ALIASES.get(model_name, model_name)
    if canonical not in MODEL_VARIANTS:
        raise ValueError(
            f"Unsupported rfdetr model '{model_name}'. Supported: "
            f"{sorted(set(MODEL_VARIANTS))}"
        )
    variant_cls, config_cls, resolution = MODEL_VARIANTS[canonical]
    return VariantInfo(
        model_name=canonical,
        variant_cls=variant_cls,
        config_cls=config_cls,
        resolution=resolution,
        is_seg="-seg-" in canonical,
        deprecated="base" in canonical,
    )


