def filter_train_kwargs(
    config: Dict[str, Any],
    log_func: Optional[Callable[[str], None]] = None,
) -> Dict[str, Any]:
    """Filter adapter/upstream kwargs against the TrainConfig whitelist.

    Drops unknown keys with a warning instead of letting pydantic
    ``extra="forbid"`` raise deep inside upstream.
    """
    _log = log_func or (lambda msg: None)
    out: Dict[str, Any] = {}
    for k, v in config.items():
        if k in _ADAPTER_CONSUMED_KEYS:
            continue
        if k in _TRAIN_WHITELIST:
            out[k] = v
        else:
            _log(f"[RFDETR] WARNING: dropping unknown train kwarg '{k}' "
                 f"(TrainConfig is extra=forbid)")
    return out


def labels_from_dataset(dataset_yaml: str | Path) -> List[str]:
    """Extract ordered class names from dataset.yaml (dict names)."""
    yaml_path = Path(dataset_yaml)
    if not yaml_path.exists():
        return []
    with open(yaml_path, encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    names = _normalize_names(data.get("names", {}))
    nc = int(data.get("nc", len(names) or 0))
    return [names[i] for i in range(nc) if i in names]
