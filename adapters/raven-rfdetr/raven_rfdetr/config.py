"""Raven -> RF-DETR configuration mapping.

- Raven model name -> rf-detr variant class / config class / default resolution
- ``dataset.yaml`` (Raven Workspace) -> ``data.yaml`` (rf-detr) idempotent projection
- train.yaml kwarg whitelist (TrainConfig is pydantic ``extra="forbid"``)
- ``pretrain_weights`` pre-check (local path or official registry name; no URL)
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

import yaml

