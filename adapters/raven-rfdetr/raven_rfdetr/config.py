def _normalize_names(names: Any) -> Dict[int, str]:
    """Normalize Raven ``names`` (dict {idx: name} or list [name, ...]) to dict."""
    if isinstance(names, dict):
        return {int(k): str(v) for k, v in names.items()}
    if isinstance(names, (list, tuple)):
        return {i: str(n) for i, n in enumerate(names)}
    raise ValueError(f"Unsupported names format: {type(names).__name__}")


def _content_sha(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def ensure_rf_yolo_layout(
    workspace_dir: Path,
    dataset_yaml: str | Path,
    log_func: Optional[Callable[[str], None]] = None,
) -> Dict[str, Any]:
    """Idempotently project Raven ``dataset.yaml`` -> rf-detr ``data.yaml``.

    Behaviour (P1-10):
    1. reads Raven dataset.yaml, normalizes ``names`` to dict;
    2. rebuilds data.yaml every call — content identical => skip write,
       different => overwrite + warn (avoids stale class maps);
    3. writes ``path`` as absolute posix path (Windows-safe);
    4. strips the ``test`` field (Raven writes ``test: ''`` which rf-detr's
       test-split parser rejects with ValueError);
    5. validates train/images + val/images exist;
    6. returns the dataset config dict (caller uses workspace as dataset_dir).

    Returns the generated data.yaml content (dict) for unit testing.
    """
    _log = log_func or (lambda msg: None)
    yaml_path = Path(dataset_yaml)
    if not yaml_path.exists():
        raise FileNotFoundError(f"dataset.yaml not found: {yaml_path}")
    with open(yaml_path, encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}

    names = _normalize_names(data.get("names", {}))
    nc = int(data.get("nc", len(names) or 0))

    # 数据根解析。Raven ``dataset.yaml`` 的 ``path`` 有三种形态，逐一尝试：
    #   1. 绝对路径（workspace 场景）
    #   2. 相对 dataset.yaml 所在目录（project 内嵌数据）
    #   3. 相对 raven-trainer 项目根（cwd）的逻辑路径（现有 project 最常见：
    #      ``path: data/workspace/d6_train_v1v2`` 实际在 raven-trainer 根下）
    # 取第一个存在 train/images 的候选；都不存在则回退到 workspace_dir。
    candidates: List[Path] = []
    raw_path = data.get("path")
    if raw_path:
        p = Path(str(raw_path))
        if p.is_absolute():
            candidates.append(p.resolve())
        else:
            candidates.append((yaml_path.parent / p).resolve())
            candidates.append((Path.cwd() / p).resolve())
    candidates.append(Path(workspace_dir).resolve())

    def _has_images(d: Path) -> bool:
        return (d / "train" / "images").exists()

    base = next((c for c in candidates if _has_images(c)), candidates[-1])

    def _split_dir(key: str, default: str) -> str:
        raw = data.get(key) or default
        p = Path(str(raw))
        if p.is_absolute():
            # 绝对 split 路径：取相对 base 的部分（若在 base 外则原样 posix）
            try:
                return str(p.relative_to(base).as_posix())
            except ValueError:
                return str(p.as_posix())
        return str(p.as_posix())

    train_dir = _split_dir("train", "train/images")
    val_dir = _split_dir("val", "val/images")

    # 剔除 test 字段（Raven 常为 test: ''，rf-detr 解析会 ValueError）
    projected = {
        "path": str(base.as_posix()),
        "train": train_dir,
        "val": val_dir,
        "nc": nc,
        "names": names,
    }

    # validate directories
    missing: List[str] = []
    for split_name, rel in (("train", train_dir), ("val", val_dir)):
        img_dir = base / rel / "images" if not rel.endswith("images") else base / rel
        if not img_dir.exists():
            missing.append(f"{split_name}: {img_dir}")
    if missing:
        _log(f"[RFDETR] WARNING: missing split directories: {', '.join(missing)}")

    # idempotent write
    out_path = base / "data.yaml"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    new_content = yaml.dump(projected, default_flow_style=False, sort_keys=False)
    if out_path.exists():
        old = out_path.read_text(encoding="utf-8")
        if old == new_content:
            _log(f"[RFDETR] data.yaml up to date: {out_path}")
            return projected
        _log(f"[RFDETR] data.yaml CHANGED (dataset updated) — overwriting: {out_path}")
    else:
        _log(f"[RFDETR] writing data.yaml: {out_path}")
    out_path.write_text(new_content, encoding="utf-8")
    return projected


